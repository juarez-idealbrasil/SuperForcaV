CREATE OR ALTER procedure SP_INDICADORES_GERAIS (
    P_ID_EMPRESA integer,
    P_DATA_INI date,
    P_DATA_FIM date,
    P_ID_REPRESENTANTE integer,
    P_ID_EQUIPE integer,
    P_ID_CLIENTE integer)
returns (
    FATURAMENTO_TOTAL numeric(18,2),
    QTD_VENDAS integer,
    TICKET_MEDIO numeric(18,2),
    CLIENTES_ATIVOS integer,
    FATURAMENTO_VARIACAO numeric(18,2),
    QTD_VENDAS_VARIACAO integer,
    TICKET_MEDIO_VARIACAO numeric(18,2),
    CLIENTES_ATIVOS_VARIACAO integer)
as
BEGIN
SELECT SUM(P.TOTAL_NEG) AS FATURAMENTO_TOTAL,
       COUNT(P.ID_PED) AS QTD_VENDAS,
       ROUND(SUM(P.TOTAL_NEG) / COUNT(P.ID_PED), 2) AS TICKET_MEDIO,
       COUNT(DISTINCT P.ID_PES) CLIENTES_ATIVOS
  FROM PEDIDO P
 WHERE P.ID_EMP = :P_ID_EMPRESA
   AND P.EMISSAO >= :P_DATA_INI
   AND P.EMISSAO <= :P_DATA_FIM
   AND P.STATUS IN (1,2)
   AND P.ID_COP = 1
   AND (:P_ID_REPRESENTANTE = 0 OR P.ID_REP = :P_ID_REPRESENTANTE)
   AND (:P_ID_CLIENTE = 0 OR P.ID_PES = :P_ID_CLIENTE)
   AND (:P_ID_EQUIPE = 0 OR EXISTS (
       SELECT 1
         FROM REPRES R
        WHERE R.ID_PES = P.ID_REP
          AND R.ID_EQU = :P_ID_EQUIPE))
  INTO :FATURAMENTO_TOTAL,
       :QTD_VENDAS,
       :TICKET_MEDIO,
       :CLIENTES_ATIVOS;

SELECT SUM(P.TOTAL_NEG) AS FATURAMENTO_TOTAL,
       COUNT(P.ID_PED) AS QTD_VENDAS,
       ROUND(SUM(P.TOTAL_NEG) / COUNT(P.ID_PED), 2) AS TICKET_MEDIO,
       COUNT(DISTINCT P.ID_PES) CLIENTES_ATIVOS
  FROM PEDIDO P
 WHERE P.ID_EMP = :P_ID_EMPRESA
   AND P.EMISSAO >= DATEADD(-1 YEAR TO :P_DATA_INI)
   AND P.EMISSAO <= DATEADD(-1 YEAR TO :P_DATA_FIM)
   AND P.STATUS IN (1,2)
   AND P.ID_COP = 1
   AND (:P_ID_REPRESENTANTE = 0 OR P.ID_REP = :P_ID_REPRESENTANTE)
   AND (:P_ID_CLIENTE = 0 OR P.ID_PES = :P_ID_CLIENTE)
   AND (:P_ID_EQUIPE = 0 OR EXISTS (
       SELECT 1
         FROM REPRES R
        WHERE R.ID_PES = P.ID_REP
          AND R.ID_EQU = :P_ID_EQUIPE))
  INTO :FATURAMENTO_VARIACAO,
       :QTD_VENDAS_VARIACAO,
       :TICKET_MEDIO_VARIACAO,
       :CLIENTES_ATIVOS_VARIACAO;

  SUSPEND;
END^

SET TERM ; ^
